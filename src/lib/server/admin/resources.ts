export const resource = (key: string) => RESOURCES.find((r) => r.key === key);

export function canAccess(r: ResourceDef, profile: { role: string; permissions: string[] }) {
  if (profile.role === 'admin') return true;
  if (profile.role !== 'staff') return false;
  return r.perm.some((p) => p !== 'admin' && profile.permissions.includes(p));
}
