export type FieldType = 'text' | 'textarea' | 'email' | 'number' | 'money' | 'percent' | 'date' | 'datetime' | 'bool' | 'select' | 'tags' | 'ref' | 'json';

export interface FieldDef {
  name: string;
  label: string;
  type: FieldType;
  options?: [string, string][];
  ref?: string; // chiave di un'altra sezione
  required?: boolean;
  readonly?: boolean;
  list?: boolean;
  help?: string;
  adminOnly?: boolean; // modificabile solo dall'amministratore
  wide?: boolean;
}

export type Perm = 'customers' | 'trade' | 'tours' | 'content' | 'admin';

export interface ResourceDef {
  key: string;
  table: string;
  label: string;
  singular: string;
  group: 'CRM' | 'Commercio' | 'Turismo' | 'Sito';
  perm: Perm[];
  title: string; // colonna mostrata come titolo
  order: string;
  search: string[];
  filters?: string[]; // campi select usati come filtri
  fixed?: Record<string, string>; // condizioni fisse (es. model = trading)
  fields: FieldDef[];
  create?: boolean;
  remove?: 'delete' | 'deactivate' | false;
  readonly?: boolean;
  related?: { resource: string; fk: string; label: string }[];
  customDetail?: boolean; // scheda con pagina dedicata (preventivi, prenotazioni, clienti)
  note?: string;
}

